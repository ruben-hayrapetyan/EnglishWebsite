"""Render chapter pages and the contents page as finished HTML.

Pages are built from _template.html: its <head>, skip link, site header,
AI credit and footer are copied, so any change to the template (for
example a new script every page must load) reaches generated pages on the
next build. The body follows layout A (reading page) for chapters and
layout B (sectioned page) for the contents page.

Output is deterministic: the same inputs always give the same bytes, and
every paragraph sits on a single line. The notes add-on finds highlights
again by their exact text, so this matters.
"""

from __future__ import annotations

import html
import re
import struct
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

from .manifest import Chapter, Manifest
from .model import (
    MARKS,
    Code,
    Document,
    Figure,
    Heading,
    Inlines,
    ListBlock,
    Paragraph,
    Quote,
    Table,
    plain_text,
)
from .normalize import IdAllocator, slugify

GENERATOR_NOTE = (
    "<!-- Generated by tools/textbook from textbook/textbook.json. "
    "Do not edit by hand: change the source or the tool, then run "
    "`python -m tools.textbook build`. -->"
)
CONTENTS_FILE = "index.html"  # the textbook is the front page
CREDIT_TOOL = "Claude Opus 5.5 (Anthropic)"
RESERVED_IDS = {"main", "site-nav", "chapter-contents", "notes"}


class TemplateError(Exception):
    pass


def esc(text: str) -> str:
    """Escape for text and double-quoted attributes (apostrophes stay readable)."""
    return html.escape(text, quote=False).replace('"', "&quot;")


# ---- Template ----------------------------------------------------------------


@dataclass(frozen=True)
class Template:
    head: str  # inner HTML of <head>, with {title} and {description} slots
    body_start: str  # skip link and site header
    body_end_footer: str  # the site footer element


def load_template(path: Path) -> Template:
    text = path.read_text(encoding="utf-8")
    head = re.search(r"<head>\n(.*?)\n</head>", text, re.S)
    start = re.search(r"<body>\n(.*?<header[^>]*data-site-header[^>]*></header>)\n", text, re.S)
    footer = re.search(r"\n(\s*<footer[^>]*data-site-footer[^>]*></footer>)\n", text)
    if not (head and start and footer):
        raise TemplateError(
            f"{path.name} no longer has the shape tools/textbook/render.py expects "
            "(<head>, skip link + data-site-header, data-site-footer). Update load_template()."
        )
    inner = head.group(1)
    if not re.search(r"<title>.*?</title>", inner) or 'name="description"' not in inner:
        raise TemplateError(f"{path.name}: the <head> needs a <title> and a meta description")
    inner = re.sub(r"<title>.*?</title>", "<title>{title}</title>", inner, count=1)
    inner = re.sub(r'(<meta name="description" content=")[^"]*(">)', r"\1{description}\2", inner, count=1)
    # Drop template-only comments such as the optional page stylesheet hint.
    inner = "\n".join(line for line in inner.split("\n") if not line.strip().startswith("<!--"))
    return Template(inner, start.group(1), footer.group(1))


def page(template: Template, *, title: str, description: str, main: str, credit: str) -> str:
    head = template.head.replace("{title}", esc(f"{title} · English Website")).replace(
        "{description}", esc(description)
    )
    return (
        "<!doctype html>\n"
        f"{GENERATOR_NOTE}\n"
        '<html lang="en">\n'
        "<head>\n"
        f"{head}\n"
        "</head>\n"
        "<body>\n"
        f"{template.body_start}\n"
        "\n"
        '  <main id="main">\n'
        f"{main}"
        "  </main>\n"
        "\n"
        '  <aside class="ai-credit" aria-label="Use of generative AI">\n'
        f'    <p class="container">{esc(credit)}</p>\n'
        "  </aside>\n"
        "\n"
        f"{template.body_end_footer}\n"
        "</body>\n"
        "</html>\n"
    )


# ---- Inline content ----------------------------------------------------------

SAFE_SCHEMES = {"http", "https", "mailto"}


def safe_href(href: str | None) -> str | None:
    """Only web, mail and relative links survive; javascript: and the like don't."""
    if not href:
        return None
    href = href.strip()
    scheme = urlsplit(href).scheme.lower()
    if scheme and scheme not in SAFE_SCHEMES:
        return None
    return href


def inline(content: Inlines) -> str:
    """Render runs with minimal, correctly nested tags."""
    out: list[str] = []
    stack: list[tuple[str, str | None]] = []  # (tag, href)
    for run in content:
        href = safe_href(run.href)
        want: list[tuple[str, str | None]] = []
        if href:
            want.append(("a", href))
        want.extend((m, None) for m in MARKS if m in run.marks)
        common = 0
        while common < len(stack) and common < len(want) and stack[common] == want[common]:
            common += 1
        while len(stack) > common:
            out.append(f"</{stack.pop()[0]}>")
        for tag, link in want[common:]:
            out.append(f'<a href="{esc(link)}">' if tag == "a" else f"<{tag}>")
            stack.append((tag, link))
        out.append(esc(run.text))
    while stack:
        out.append(f"</{stack.pop()[0]}>")
    return "".join(out)


# ---- Images ------------------------------------------------------------------


def image_size(data: bytes, ext: str) -> tuple[int, int] | None:
    """Width and height from a PNG or JPEG header, without decoding."""
    if ext == "png" and data[:8] == b"\x89PNG\r\n\x1a\n" and data[12:16] == b"IHDR":
        return struct.unpack(">II", data[16:24])
    if ext == "jpg" and data[:2] == b"\xff\xd8":
        i = 2
        while i + 9 < len(data):
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in (0xD8, 0x01) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            length = struct.unpack(">H", data[i + 2 : i + 4])[0]
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                height, width = struct.unpack(">HH", data[i + 5 : i + 9])
                return width, height
            i += 2 + length
    return None


# ---- Chapter body ------------------------------------------------------------


@dataclass
class RenderedChapter:
    html: str
    images: dict[str, bytes]  # repo-relative path -> bytes
    warnings: list[str]


class BodyRenderer:
    def __init__(self, chapter: Chapter):
        self.chapter = chapter
        self.ids = IdAllocator(RESERVED_IDS)
        self.images: dict[str, bytes] = {}
        self.warnings: list[str] = []
        self.sections: list[tuple[str, str]] = []  # (id, text) of each h2
        self.figure_n = 0
        self.table_n = 0

    def blocks(self, blocks, indent: str) -> list[str]:
        out = []
        for block in blocks:
            out.extend(self.block(block, indent))
        return out

    def block(self, block, ind: str) -> list[str]:
        if isinstance(block, Heading):
            text = plain_text(block.content)
            block.id = self.ids.take(slugify(text))
            if block.level == 2:
                self.sections.append((block.id, text))
            tag = f"h{block.level}"
            return [f'{ind}<{tag} id="{block.id}">{inline(block.content)}</{tag}>']
        if isinstance(block, Paragraph):
            return [f"{ind}<p>{inline(block.content)}</p>"]
        if isinstance(block, ListBlock):
            return self.list_block(block, ind)
        if isinstance(block, Figure):
            return self.figure(block, ind)
        if isinstance(block, Table):
            return self.table(block, ind)
        if isinstance(block, Quote):
            lines = [f"{ind}<blockquote>"]
            lines += [f"{ind}  <p>{inline(p)}</p>" for p in block.content]
            return lines + [f"{ind}</blockquote>"]
        if isinstance(block, Code):
            return [f"{ind}<pre><code>{esc(block.text)}</code></pre>"]
        raise TypeError(f"cannot render {type(block).__name__}")  # pragma: no cover

    def list_block(self, block: ListBlock, ind: str) -> list[str]:
        tag = "ol" if block.ordered else "ul"
        start = f' start="{block.start}"' if block.ordered and block.start != 1 else ""
        lines = [f"{ind}<{tag}{start}>"]
        for item in block.items:
            if item.children:
                lines.append(f"{ind}  <li>{inline(item.content)}")
                for child in item.children:
                    lines += self.list_block(child, ind + "    ")
                lines.append(f"{ind}  </li>")
            else:
                lines.append(f"{ind}  <li>{inline(item.content)}</li>")
        return lines + [f"{ind}</{tag}>"]

    def figure(self, fig: Figure, ind: str) -> list[str]:
        self.figure_n += 1
        base = slugify(fig.label) if fig.label else f"figure-{self.figure_n}"
        fig.id = self.ids.take(base)
        name = f"assets/img/chapter-{self.chapter.id}-{fig.id}.{fig.image.ext}"
        self.images[name] = fig.image.data
        alt = self.alt_for(fig)
        size = image_size(fig.image.data, fig.image.ext)
        dims = f' width="{size[0]}" height="{size[1]}"' if size else ""
        lines = [f'{ind}<figure id="{fig.id}">', f'{ind}  <img src="{name}" alt="{esc(alt)}"{dims} loading="lazy">']
        if fig.caption or fig.label:
            label = f"<strong>{esc(fig.label)}.</strong> " if fig.label else ""
            lines.append(f"{ind}  <figcaption>{label}{inline(fig.caption)}</figcaption>")
        return lines + [f"{ind}</figure>"]

    def alt_for(self, fig: Figure) -> str:
        override = self.chapter.figures.get(fig.id, {}).get("alt")
        if override:
            return override
        if fig.alt:
            return fig.alt
        caption = plain_text(fig.caption).strip()
        where = fig.label or fig.id
        if caption:
            self.warnings.append(
                f'{where}: no alt text in the source, so the caption was used; add '
                f'"figures": {{"{fig.id}": {{"alt": "..."}}}} to this chapter in textbook.json'
            )
            return re.split(r"(?<=[.!?])\s", caption, maxsplit=1)[0]
        self.warnings.append(
            f'{where}: no alt text and no caption; add "figures": {{"{fig.id}": {{"alt": "..."}}}} in textbook.json'
        )
        return ""

    def table(self, table: Table, ind: str) -> list[str]:
        self.table_n += 1
        base = slugify(table.label) if table.label else f"table-{self.table_n}"
        table.id = self.ids.take(base)
        lines = [f'{ind}<table id="{table.id}" tabindex="0">']
        if table.caption or table.label:
            label = f"<strong>{esc(table.label)}.</strong> " if table.label else ""
            lines.append(f"{ind}  <caption>{label}{inline(table.caption)}</caption>")
        header, *rows = table.rows
        lines.append(f"{ind}  <thead>")
        lines.append(f"{ind}    <tr>" + "".join(f'<th scope="col">{inline(c)}</th>' for c in header) + "</tr>")
        lines.append(f"{ind}  </thead>")
        if rows:
            lines.append(f"{ind}  <tbody>")
            for row in rows:
                lines.append(f"{ind}    <tr>" + "".join(f"<td>{inline(c)}</td>" for c in row) + "</tr>")
            lines.append(f"{ind}  </tbody>")
        return lines + [f"{ind}</table>"]


def title_html(title: str, highlight: str | None) -> str:
    if not highlight or highlight not in title:
        return esc(title)
    before, _, after = title.partition(highlight)
    return f'{esc(before)}<mark class="highlight--draw">{esc(highlight)}</mark>{esc(after)}'


def names(manifest: Manifest, slugs: list[str], site_root: Path, link: bool) -> str:
    parts = []
    for slug in slugs:
        name = esc(manifest.authors[slug])
        if link and (site_root / f"author-{slug}.html").is_file():
            parts.append(f'<a href="author-{slug}.html">{name}</a>')
        else:
            parts.append(name)
    if len(parts) <= 2:
        return " and ".join(parts)
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def render_chapter(
    manifest: Manifest,
    chapter: Chapter,
    doc: Document,
    template: Template,
    site_root: Path,
    available: list[Chapter],
) -> RenderedChapter:
    body = BodyRenderer(chapter)
    article = body.blocks(doc.blocks, " " * 8)
    if doc.notes:
        article.append('        <h2 id="notes">Notes</h2>')
        article.append("        <ol>")
        article += [f"          <li>{inline(n)}</li>" for n in doc.notes]
        article.append("        </ol>")
    if not article:
        body.warnings.append("the source has no content after the chapter title")

    unit = manifest.unit(chapter.unit)
    m: list[str] = ['    <div class="container container--narrow page-body">']
    m.append('      <header class="page-header" data-read-aloud>')
    m.append(f'        <p class="page-header__meta">Chapter {chapter.number} · {esc(unit.title)}</p>')
    m.append(f'        <h1 class="page-header__title">{title_html(chapter.title, chapter.highlight)}</h1>')
    if chapter.summary:
        m.append(f'        <p class="page-header__lede">{esc(chapter.summary)}</p>')
    m.append(f"        <p>By {names(manifest, chapter.authors, site_root, link=True)}</p>")
    m.append("      </header>")

    if len(body.sections) >= 2:
        m.append('      <nav class="chapter-nav" aria-labelledby="chapter-contents" data-read-aloud-skip>')
        m.append('        <h2 class="chapter-nav__title" id="chapter-contents">In this chapter</h2>')
        m.append('        <ol class="chapter-nav__list">')
        for sid, text in body.sections:
            m.append(f'          <li><a class="chapter-nav__link" href="#{sid}">{esc(text)}</a></li>')
        m.append("        </ol>")
        m.append("      </nav>")

    m.append('      <article class="prose" data-read-aloud>')
    m += article
    m.append("      </article>")

    m.append('      <p class="cluster">')
    study = f"study-{chapter.id}.html"
    if (site_root / study).is_file():
        m.append(f'        <a class="button" href="{study}">Practice with the study kit</a>')
    m.append(f'        <a class="button button--secondary" href="{CONTENTS_FILE}">See all chapters</a>')
    m.append("      </p>")

    index = available.index(chapter)
    prev_ch = available[index - 1] if index > 0 else None
    next_ch = available[index + 1] if index + 1 < len(available) else None
    if prev_ch or next_ch:
        m.append('      <nav class="chapter-nav chapter-nav--pager" aria-label="Chapters">')
        if prev_ch:
            m.append(f'        <a class="chapter-nav__step" href="{prev_ch.filename}" rel="prev">')
            m.append('          <span class="chapter-nav__label">Previous chapter</span>')
            m.append(f'          <span class="chapter-nav__name">{esc(prev_ch.title)}</span>')
            m.append("        </a>")
        if next_ch:
            m.append(f'        <a class="chapter-nav__step chapter-nav__step--next" href="{next_ch.filename}" rel="next">')
            m.append('          <span class="chapter-nav__label">Next chapter</span>')
            m.append(f'          <span class="chapter-nav__name">{esc(next_ch.title)}</span>')
            m.append("        </a>")
        m.append("      </nav>")
    m.append("    </div>")

    authors_plain = names(manifest, chapter.authors, site_root, link=False)
    description = chapter.summary or f"Chapter {chapter.number} of {manifest.title}, by {html.unescape(authors_plain)}."
    credit = (
        f"Generative AI: {CREDIT_TOOL} wrote the converter (tools/textbook) that turned this chapter's source "
        "file into this page; it did not write the chapter. "
        + (chapter.ai_credit or "The chapter's authors have not yet stated whether they used generative AI.")
    )
    return RenderedChapter(
        page(template, title=chapter.title, description=description, main="\n".join(m) + "\n", credit=credit),
        body.images,
        body.warnings,
    )


def render_contents(manifest: Manifest, template: Template, site_root: Path, available: set[str]) -> str:
    total = len(manifest.chapters)
    m = ['    <div class="container">', '      <header class="page-header">']
    m.append(
        f'        <p class="page-header__meta">{total} chapter{"s" if total != 1 else ""} · '
        f'{len(manifest.units)} unit{"s" if len(manifest.units) != 1 else ""}</p>'
    )
    m.append(f'        <h1 class="page-header__title">{title_html(manifest.title, manifest.highlight)}</h1>')
    m.append(f'        <p class="page-header__lede">{esc(manifest.lede)}</p>')
    m.append("      </header>")
    m.append("    </div>")
    for unit in manifest.units:
        chapters = [c for c in manifest.chapters if c.unit == unit.id]
        if not chapters:
            continue
        m.append("")
        m.append(f'    <section class="section" aria-labelledby="unit-{unit.id}">')
        m.append('      <div class="container">')
        m.append('        <div class="section__header">')
        m.append(f'          <h2 id="unit-{unit.id}">{esc(unit.title)}</h2>')
        m.append("        </div>")
        m.append('        <div class="grid">')
        for c in chapters:
            ready = c.id in available
            m.append(f'          <article class="card" id="{c.id}">')
            m.append(f'            <p class="card__meta">Chapter {c.number}</p>')
            if ready:
                m.append(f'            <h3 class="card__title"><a href="{c.filename}">{esc(c.title)}</a></h3>')
            else:
                m.append(f'            <h3 class="card__title">{esc(c.title)}</h3>')
            m.append(f'            <p class="card__body">{names(manifest, c.authors, site_root, link=False)}</p>')
            if ready:
                m.append('            <span class="card__footer" aria-hidden="true">Read the chapter &rarr;</span>')
            else:
                m.append('            <p class="cluster"><span class="tag">Coming soon</span></p>')
            m.append("          </article>")
        m.append("        </div>")
        m.append("      </div>")
        m.append("    </section>")
    credit = (
        f"Generative AI: {CREDIT_TOOL} wrote the converter (tools/textbook) that generates this page "
        "and drafted its text."
    )
    return page(
        template,
        title="Textbook",
        description=manifest.description,
        main="\n".join(m) + "\n",
        credit=credit,
    )
